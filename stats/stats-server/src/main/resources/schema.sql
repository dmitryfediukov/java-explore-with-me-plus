CREATE TABLE IF NOT EXISTS endpoint_hits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app TEXT NOT NULL,
    uri TEXT NOT NULL,
    ip TEXT NOT NULL,
    hit_time TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_endpoint_hits_time ON endpoint_hits (hit_time);
CREATE INDEX IF NOT EXISTS idx_endpoint_hits_uri_time ON endpoint_hits (uri, hit_time);
